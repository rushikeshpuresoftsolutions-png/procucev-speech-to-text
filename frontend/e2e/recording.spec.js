import { test, expect } from '@playwright/test'

test('transcribes browser microphone audio, saves, reopens, edits and deletes the result', async ({ page }) => {
  const title = 'Browser recording ' + Date.now()
  await page.goto('/')
  await page.getByRole('link', { name: 'New transcription' }).click()
  await page.getByLabel('Speech language').selectOption('en')
  await page.getByRole('button', { name: 'Start recording' }).click()
  const transcript = page.getByLabel('Transcription', { exact: true })
  await expect(transcript).toHaveValue(/project|meeting|team/i, { timeout: 85_000 })
  await page.getByRole('button', { name: 'Stop recording' }).click()
  await expect(transcript).toBeEditable({ timeout: 40_000 })
  await page.getByLabel('Title', { exact: true }).fill(title)
  await page.getByRole('button', { name: 'Save transcription' }).click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('link', { name: 'Edit', exact: true }).click()
  await page.getByLabel('Transcription', { exact: true }).fill('आज हमारी project meeting है।')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByText('आज हमारी project meeting है।', { exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: 'Workspace' }).getByRole('link', { name: 'History' }).click()
  await page.getByLabel('Search transcriptions').fill(title)
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Delete ' + title, exact: true }).click()
  await expect(page.getByText('No matching transcriptions')).toBeVisible()
})
